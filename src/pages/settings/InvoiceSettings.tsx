import { useEffect, useState } from "react";
import { Lock } from "lucide-react";
import SettingsLayout from "./SettingsLayout";
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from "@/components/ui/card";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { useI18n } from "@/contexts/I18nContext";
import { useBranch } from "@/contexts/BranchContext";
import { supabase } from "@/integrations/supabase/client";

// Mirrors public.branch_invoice_code(). The order matters: the generator strips
// non-ASCII before upper-casing, so "ß" becomes the branch fallback there but
// would become "SS" if this uppercased first.
export function invoiceBranchCode(code: string | null | undefined, branchId: string) {
  const cleaned = (code ?? "").replace(/[^A-Za-z0-9]/g, "").toUpperCase();
  if (cleaned) return cleaned;
  const hex = branchId.replace(/-/g, "").slice(0, 4).toUpperCase();
  return hex ? `B${hex}` : "";
}

export default function InvoiceSettings() {
  const { t, lang } = useI18n();
  const { branches, currentBranchId } = useBranch();
  const [branchId, setBranchId] = useState(currentBranchId ?? "");
  const [rawCode, setRawCode] = useState<string | null>(null);
  const isArabic = lang === "ar";

  useEffect(() => {
    if (!branchId) { setRawCode(null); return; }
    let cancelled = false;
    supabase.from("branches").select("code").eq("id", branchId).maybeSingle()
      .then(({ data }) => {
        if (!cancelled) setRawCode((data as { code?: string | null } | null)?.code ?? null);
      });
    return () => { cancelled = true; };
  }, [branchId]);

  const code = branchId ? invoiceBranchCode(rawCode, branchId) : "";
  const year = new Date().getFullYear();
  const example = code ? `INV-${code}-${year}-0001` : `INV-<BRANCH>-${year}-0001`;

  const copy = {
    numbering: isArabic ? "الترقيم والتسلسل" : "Numbering & Sequencing",
    numberingDesc: isArabic
      ? "تُمنح أرقام الفواتير تلقائيًا عند إصدار الفاتورة، ولا يمكن تعديلها من هنا."
      : "Invoice numbers are assigned by the system when an invoice is issued. They cannot be edited here.",
    format: isArabic ? "الصيغة" : "Format",
    example: isArabic ? "مثال" : "Example",
    branchRule: isArabic ? "رمز الفرع في الترقيم" : "The branch's invoice code",
    branchKnown: isArabic ? "هذا الفرع" : "this branch",
    branchUnknown: isArabic ? "يُحدَّد تلقائيًا لعدم ضبط رمز للفرع" : "assigned automatically because no branch code is set",
    yearRule: isArabic ? "السنة الميلادية؛ يبدأ التسلسل من 0001 مع كل عام جديد" : "The calendar year; the sequence restarts at 0001 every year",
    seqRule: isArabic ? "تسلسل من أربعة أرقام يُكمَّل بالأصفار ويُشترك بين كل فواتير الفرع" : "A four-digit sequence, zero-padded, shared by every invoice in the branch",
    autoNote: isArabic
      ? "تُمنح الأرقام تلقائيًا وقد يعيد النظام اشتقاقها؛ لا يمكن تعديلها يدويًا."
      : "Numbers are assigned automatically and may be re-derived by the system. They are not editable by hand.",
    readOnlyTitle: isArabic ? "صفحة للقراءة فقط" : "Read-only page",
    readOnlyBody: isArabic
      ? "خيارات الضريبة والعرض والنصوص التي كانت هذه الصفحة تعرضها غير موصولة بإصدار الفواتير بعد، وعرضها كحقول قابلة للتعديل لا يغيّر شيئًا. لذلك لا تعرض الصفحة حقول تعديل، وترقيم الفواتير نفسه يتولاه نظام قاعدة البيانات."
      : "The tax, display and text options this page used to offer are not connected to invoice generation yet, so editable fields here would change nothing. The page therefore shows no editable fields — invoice numbering itself is generated by the database.",
  };

  return (
    <SettingsLayout>
      <div className="space-y-6">
        <div className="flex items-center justify-between flex-wrap gap-3 bg-background border-b border-border/60 py-3 -mx-1 px-1">
          <h1 className="text-2xl font-bold">{t("invoiceSettings")}</h1>
          <Select value={branchId} onValueChange={setBranchId}>
            <SelectTrigger className="w-56"><SelectValue placeholder={t("branch")} /></SelectTrigger>
            <SelectContent>{branches.map(b => <SelectItem key={b.id} value={b.id}>{lang === "ar" ? b.name_ar : b.name_en}</SelectItem>)}</SelectContent>
          </Select>
        </div>

        <Card>
          <CardHeader>
            <CardTitle>{copy.numbering}</CardTitle>
            <CardDescription>{copy.numberingDesc}</CardDescription>
          </CardHeader>
          <CardContent className="space-y-5">
            <div className="space-y-2">
              <p className="text-xs font-medium text-muted-foreground">{copy.format}</p>
              <code dir="ltr" className="block rounded-lg border bg-muted/30 px-4 py-3 font-mono text-sm sm:text-base">INV-&lt;BRANCH&gt;-&lt;YEAR&gt;-&lt;SEQ&gt;</code>
            </div>
            <div className="space-y-2">
              <p className="text-xs font-medium text-muted-foreground">{copy.example}</p>
              <code dir="ltr" className="block rounded-lg border bg-muted/30 px-4 py-3 font-mono text-sm sm:text-base">{example}</code>
            </div>
            <ul className="space-y-2 text-sm text-muted-foreground">
              <li><span className="font-medium text-foreground">BRANCH</span> — {copy.branchRule} ({code ? `${copy.branchKnown}: ${code}` : copy.branchUnknown}).</li>
              <li><span className="font-medium text-foreground">YEAR</span> — {copy.yearRule}.</li>
              <li><span className="font-medium text-foreground">SEQ</span> — {copy.seqRule}.</li>
            </ul>
            <p className="text-xs text-muted-foreground">{copy.autoNote}</p>
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle className="flex items-center gap-2"><Lock className="size-4" />{copy.readOnlyTitle}</CardTitle>
            <CardDescription>{copy.readOnlyBody}</CardDescription>
          </CardHeader>
        </Card>
      </div>
    </SettingsLayout>
  );
}
